const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const prisma = require('../config/prisma');

const JWT_SECRET = process.env.JWT_SECRET || 'kawinan_super_secure_jwt_token_secret_key_2026';

function generateToken(user) {
  return jwt.sign(
    {
      id: user.id.toString(),
      email: user.email,
      name: user.name,
      role: user.role,
    },
    JWT_SECRET,
    { expiresIn: '7d' }
  );
}

class AuthController {
  async login(req, res) {
    try {
      const { email, password } = req.body;

      if (!email || !password) {
        return res.status(422).json({
          message: 'The given data was invalid.',
          errors: { email: ['Email dan password wajib diisi.'] },
        });
      }

      const user = await prisma.users.findUnique({
        where: { email },
      });

      if (!user) {
        return res.status(422).json({
          message: 'These credentials do not match our records.',
          errors: { email: ['Kredensial tersebut tidak cocok dengan data kami.'] },
        });
      }

      // bcryptjs supports standard bcrypt as well as $2y$ prefix generated by PHP
      const isMatch = await bcrypt.compare(password, user.password);
      if (!isMatch) {
        return res.status(422).json({
          message: 'These credentials do not match our records.',
          errors: { password: ['Kata sandi yang Anda masukkan salah.'] },
        });
      }

      const token = generateToken(user);

      res.cookie('token', token, {
        httpOnly: true,
        maxAge: 7 * 24 * 60 * 60 * 1000,
        sameSite: 'lax',
      });

      return res.json({
        message: 'Login berhasil.',
        user: {
          id: user.id,
          name: user.name,
          email: user.email,
          role: user.role,
        },
        token,
      });
    } catch (error) {
      console.error('Login error:', error);
      return res.status(500).json({ message: 'Terjadi kesalahan pada server saat login.' });
    }
  }

  async register(req, res) {
    try {
      const { name, email, password, password_confirmation } = req.body;

      if (!name || !email || !password) {
        return res.status(422).json({
          message: 'The given data was invalid.',
          errors: { email: ['Seluruh field wajib diisi.'] },
        });
      }

      if (password_confirmation && password !== password_confirmation) {
        return res.status(422).json({
          message: 'The given data was invalid.',
          errors: { password: ['Konfirmasi kata sandi tidak cocok.'] },
        });
      }

      const existing = await prisma.users.findUnique({ where: { email } });
      if (existing) {
        return res.status(422).json({
          message: 'The email has already been taken.',
          errors: { email: ['Alamat email ini sudah terdaftar.'] },
        });
      }

      const hashedPassword = await bcrypt.hash(password, 12);

      const user = await prisma.users.create({
        data: {
          name,
          email,
          password: hashedPassword,
          role: 'user',
          created_at: new Date(),
          updated_at: new Date(),
        },
      });

      const token = generateToken(user);

      res.cookie('token', token, {
        httpOnly: true,
        maxAge: 7 * 24 * 60 * 60 * 1000,
        sameSite: 'lax',
      });

      return res.status(201).json({
        message: 'Pendaftaran berhasil.',
        user: {
          id: user.id,
          name: user.name,
          email: user.email,
          role: user.role,
        },
        token,
      });
    } catch (error) {
      console.error('Register error:', error);
      return res.status(500).json({ message: 'Gagal melakukan pendaftaran akun.' });
    }
  }

  async me(req, res) {
    const user = req.user;
    return res.json({
      user: {
        id: user.id,
        name: user.name,
        email: user.email,
        role: user.role,
      },
    });
  }

  async logout(req, res) {
    res.clearCookie('token');
    return res.json({ message: 'Berhasil logout.' });
  }

  async updateProfile(req, res) {
    try {
      const user = req.user;
      const { name, email, password, current_password } = req.body;

      const dataToUpdate = {
        updated_at: new Date(),
      };

      if (name) dataToUpdate.name = name;

      if (email && email !== user.email) {
        const check = await prisma.users.findUnique({ where: { email } });
        if (check && check.id !== user.id) {
          return res.status(422).json({
            message: 'Email sudah digunakan akun lain.',
            errors: { email: ['Email sudah digunakan akun lain.'] },
          });
        }
        dataToUpdate.email = email;
      }

      if (password) {
        if (current_password) {
          const isMatch = await bcrypt.compare(current_password, user.password);
          if (!isMatch) {
            return res.status(422).json({
              message: 'Password saat ini salah.',
              errors: { current_password: ['Password saat ini salah.'] },
            });
          }
        }
        dataToUpdate.password = await bcrypt.hash(password, 12);
      }

      const updated = await prisma.users.update({
        where: { id: user.id },
        data: dataToUpdate,
      });

      return res.json({
        message: 'Profil berhasil diperbarui.',
        user: {
          id: updated.id,
          name: updated.name,
          email: updated.email,
          role: updated.role,
        },
      });
    } catch (error) {
      console.error('Update profile error:', error);
      return res.status(500).json({ message: 'Gagal memperbarui profil.' });
    }
  }
}

module.exports = new AuthController();
